/*
  Примечание по структуре NUMBQ:
    - a — числитель (NUMBZ по значению)
    - b — знаменатель (NUMBN по значению), всегда > 0

  Примечание по структуре NUMBN:
    - A[0]   — младшая цифра числа (единицы)
    - A[n-1] — старшая цифра числа
    - n      — количество цифр в числе

  Знаменатель равен 1: b.n == 1 && b.A[0] == 1.
*/

/*
  INT_Q_B

  Параметры:
    1) NUMBQ* a - рациональное число

  Возвращает int: 1 - знаменатель равен 1, 0 - иначе, -1 при ошибке
*/
int INT_Q_B(NUMBQ* a) {
    if (a == NULL) return -1;
    if (a->b.A == NULL || a->b.n <= 0) return -1;

    return a->b.n == 1 && a->b.A[0] == 1;
}
